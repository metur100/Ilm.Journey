/** The namespace `game.<id>` of one salah-prayers game: its own title/description/howTo plus the shared texts. */
export function prayerNamespace(id: string, own: { en: GameTexts; de: GameTexts; bs: GameTexts }) {
  return defineNamespace(`game.${id}`, {
    en: { ...en, ...own.en } as Record<keyof typeof en | keyof GameTexts, string>,
    de: { ...de, ...own.de },
    bs: { ...bs, ...own.bs },
  });
}

